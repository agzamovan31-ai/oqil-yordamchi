async function initDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      role TEXT NOT NULL DEFAULT 'user',
      permissions TEXT NOT NULL DEFAULT '{}',
      created_by BIGINT,
      created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
    );
  `);

  await pool.query(`
    DO $$
    BEGIN
      IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_users_created_by'
      ) THEN
        ALTER TABLE users
          ADD CONSTRAINT fk_users_created_by
          FOREIGN KEY (created_by)
          REFERENCES users(id)
          DEFERRABLE INITIALLY DEFERRED;
      END IF;
    END $$;
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_lower
      ON users (LOWER(username));
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_users_role
      ON users (role);
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_users_created_by
      ON users (created_by);
  `);

  const ownerName = process.env.OWNER_USERNAME.trim();
  const { rows: ownerRows } = await pool.query(
    "SELECT * FROM users WHERE LOWER(username) = LOWER($1) LIMIT 1",
    [ownerName]
  );

  const owner = ownerRows[0];

  if (owner && owner.role !== "owner") {
    throw new Error("EGA username'i band. Boshqa OWNER_USERNAME tanlang.");
  }

  const { rows: anotherOwnerRows } = await pool.query(
    "SELECT id FROM users WHERE role = 'owner' LIMIT 1"
  );

  const anotherOwner = anotherOwnerRows[0];

  if (!owner && anotherOwner) {
    throw new Error("Bazadagi EGA hisobini tekshiring.");
  }

  if (!owner) {
    const hash = bcrypt.hashSync(process.env.OWNER_PASSWORD, 12);

    await pool.query(
      "INSERT INTO users (username, password_hash, role, permissions) VALUES ($1, $2, 'owner', '{}')",
      [ownerName, hash]
    );

    console.log("EGA akkaunti yaratildi.");
  }
}


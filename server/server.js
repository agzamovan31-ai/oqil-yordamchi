app.post("/api/speech", tekshirish, speechLimit, async (req, res) => {
  try {
    const matn = typeof req.body?.text === "string"
      ? req.body.text.trim()
      : "";

    if (!matn) {
      return res.status(400).json({
        error: "Ovozga aylantirish uchun matn yo‘q."
      });
    }

    if (matn.length > 6000) {
      return res.status(400).json({
        error: "Matn juda uzun. Uni qisqartirib qayta urinib ko‘ring."
      });
    }

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({
        error: "Gemini API kaliti topilmadi."
      });
    }

    const response = await fetch(
      "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash-tts:generateContent",
      {
        method: "POST",
        signal: AbortSignal.timeout(90000),
        headers: {
          "Content-Type": "application/json",
          "x-goog-api-key": process.env.GEMINI_API_KEY
        },
        body: JSON.stringify({
          contents: [{
            role: "user",
            parts: [{
              text: matn,
              speechMetadata: {
                style: "Speak clearly and slowly in Northern Uzbek, as close as possible to standard Uzbek used in Uzbekistan. Use Uzbek pronunciation, not Russian pronunciation. Read numbers and Roman numerals as Uzbek words. Use a calm, natural educational narrator voice."
              }
            }]
          }],
          generationConfig: {
            responseModalities: ["AUDIO"],
            speechConfig: {
              voiceConfig: {
                voice: "Kore"
              }
            }
          }
        })
      }
    );

    const data = await response.json();

    if (!response.ok) {
      console.error("Gemini TTS xatosi:", data.error?.message || data);
      return res.status(502).json({
        error: "Ovoz yaratilmadi. Gemini TTS modeli yoki API ruxsatini tekshirish kerak."
      });
    }

    const audioPart = data.candidates?.[0]?.content?.parts?.find(
      part => part.inlineData?.data
    );

    if (!audioPart?.inlineData?.data) {
      console.error("Gemini TTS audio qaytarmadi:", JSON.stringify(data).slice(0, 1000));
      return res.status(502).json({
        error: "Gemini ovozli javob qaytarmadi."
      });
    }

    res.json({
      audio: audioPart.inlineData.data,
      mimeType: audioPart.inlineData.mimeType || "audio/wav"
    });

  } catch (error) {
    console.error("Ovoz yaratish xatosi:", error.name, error.message);

    if (error.name === "TimeoutError" || error.name === "AbortError") {
      return res.status(504).json({
        error: "Ovoz yaratish uzoq davom etdi. Qayta urinib ko‘ring."
      });
    }

    return res.status(500).json({
      error: "Ovoz serveriga ulanib bo‘lmadi."
    });
  }
});


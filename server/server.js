// Token yaratish
function tokenYaratish(user) {
  return jwt.sign(
    { id: user.id },
    process.env.JWT_SECRET,
    { expiresIn: "7d" }
  );
}

// Foydalanuvchini tekshirish
async function tekshirish(req, res, next) {
  try {
    const token = req.headers.authorization?.split(" ")[1];

    if (!token) {
      return res.status(401).json({
        error: "Tizimga kiring."
      });
    }

    const decoded = jwt.verify(token, process.env.JWT_SECRET);

    const { rows } = await pool.query(
      "SELECT id, username, email, role, permissions, subscription_plan, class_level, subscription_status, subscription_until FROM users WHERE id = $1",
      [decoded.id]
    );

    const user = rows[0];

    if (!user) {
      return res.status(401).json({
        error: "Hisob topilmadi."
      });
    }

    req.user = {
      ...user,
      role: getEffectiveUserRole(user)
    };
    next();

  } catch {
    res.status(401).json({
      error: "Kirish muddati tugagan. Qayta kiring."
    });
  }
}


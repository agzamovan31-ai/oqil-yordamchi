app.post("/api/translate", tekshirish, async (req, res) => {
  try {
    const { text, from = "auto", to = "uz" } = req.body || {};

    if (typeof text !== "string" || !text.trim()) {
      return res.status(400).json({ error: "Matn kerak." });
    }

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({ error: "Gemini API kaliti topilmadi." });
    }

    const prompt = `Translate the following text from ${from} to ${to}. Return ONLY the translation, no extra text:\n\n${text.trim()}`;

    const response = await fetch(
      "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent",
      {
        method: "POST",
        signal: AbortSignal.timeout(30000),
        headers: {
          "Content-Type": "application/json",
          "x-goog-api-key": process.env.GEMINI_API_KEY
        },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: { temperature: 0, maxOutputTokens: 1000 }
        })
      }
    );

    const data = await response.json();

    if (!response.ok) {
      console.error("Tarjima xatosi:", data.error?.message);
      return res.status(502).json({ error: "Tarjima amalga oshirilmadi." });
    }

    const translation = data.candidates?.[0]?.content?.parts?.map(p => p.text || "").join("").trim();

    if (!translation) {
      return res.status(502).json({ error: "Tarjima natijasi bo‘sh." });
    }

    res.json({ translation });

  } catch (error) {
    console.error("Translate xatosi:", error);
    if (error.name === "TimeoutError" || error.name === "AbortError") {
      return res.status(504).json({ error: "Tarjima uzoq davom etdi." });
    }
    res.status(500).json({ error: "Tarjima amalga oshirilmadi." });
  }
});


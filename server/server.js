app.post("/api/auth/login", loginLimit, async (req, res) => {
  const { username, password } = req.body || {};

  if (
    typeof username !== "string" ||
    typeof password !== "string"
  ) {
    return res.status(400).json({
      error: "Username va parolni kiriting."
    });
  }

  const normalizedUsername = username.trim();
  const { rows } = await pool.query(
    "SELECT * FROM users WHERE LOWER(username) = LOWER($1) OR LOWER(email) = LOWER($2) LIMIT 1",
    [normalizedUsername, normalizedUsername]
  );

  const user = rows[0];

  if (!user || !bcrypt.compareSync(password, user.password_hash)) {
    return res.status(401).json({
      error: "Username yoki parol noto‘g‘ri."
    });
  }

  const effectiveRole = getEffectiveUserRole(user);

  res.json({
    xabar: "Muvaffaqiyatli kirdingiz.",
    token: tokenYaratish({ ...user, role: effectiveRole }),
    user: {
      id: user.id,
      username: user.username,
      email: user.email || null,
      role: effectiveRole,
      subscription_plan: normalizeSubscriptionPlan(user.subscription_plan),
      class_level: Number(user.class_level || 1),
      subscription_status: user.subscription_status || "demo"
    }
  });
});


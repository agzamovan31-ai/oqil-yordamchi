app.post("/api/auth/register", async (req, res) => {
  try {
    const { username, password } = req.body || {};

    if (
      typeof username !== "string" ||
      !/^[a-zA-Z0-9_-]{3,20}$/.test(username.trim())
    ) {
      return res.status(400).json({
        error: "Username 3–20 ta belgi bo‘lsin."
      });
    }

    if (
      typeof password !== "string" ||
      password.length < 8 ||
      password.length > 72
    ) {
      return res.status(400).json({
        error: "Parol 8–72 ta belgi bo‘lishi kerak."
      });
    }

    const trimmedUsername = username.trim();
    const existing = await pool.query(
      "SELECT id FROM users WHERE LOWER(username) = LOWER($1) LIMIT 1",
      [trimmedUsername]
    );

    if (existing.rowCount > 0) {
      return res.status(409).json({
        error: "Bu username band."
      });
    }

    const hash = bcrypt.hashSync(password, 12);

    const result = await pool.query(
      "INSERT INTO users (username, password_hash) VALUES ($1, $2) RETURNING id, username, role",
      [trimmedUsername, hash]
    );

    const user = result.rows[0];

    res.status(201).json({
      xabar: "Hisob yaratildi.",
      token: tokenYaratish(user),
      user
    });

  } catch (error) {
    if (error.code === "23505") {
      return res.status(409).json({
        error: "Bu username band."
      });
    }

    console.error(error);

    res.status(500).json({
      error: "Hisob yaratilmadi."
    });
  }
});

// Tizimga kirish
app.post("/api/auth/login", loginLimit, async (req, res) => {
  const { username, password } = req.body || {};

  if (
    typeof username !== "string" ||
    typeof password !== "string"
  ) {
    return res.status(400).json({
      error: "Username va parolni kiriting."
    });
  }

  const { rows } = await pool.query(
    "SELECT * FROM users WHERE LOWER(username) = LOWER($1) LIMIT 1",
    [username.trim()]
  );

  const user = rows[0];

  if (!user || !bcrypt.compareSync(password, user.password_hash)) {
    return res.status(401).json({
      error: "Username yoki parol noto‘g‘ri."
    });
  }

  res.json({
    xabar: "Muvaffaqiyatli kirdingiz.",
    token: tokenYaratish(user),
    user: {
      id: user.id,
      username: user.username,
      role: user.role
    }
  });
});


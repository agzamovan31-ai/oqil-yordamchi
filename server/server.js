// Token yaratish
function tokenYaratish(user) {
  return jwt.sign(
    { id: user.id },
    process.env.JWT_SECRET,
    { expiresIn: "7d" }
  );
}

// Foydalanuvchini tekshirish
async function tekshirish(req, res, next) {
  try {
    const token = req.headers.authorization?.split(" ")[1];

    if (!token) {
      return res.status(401).json({
        error: "Tizimga kiring."
      });
    }

    const decoded = jwt.verify(token, process.env.JWT_SECRET);

    const { rows } = await pool.query(
      "SELECT id, username, role, permissions FROM users WHERE id = $1",
      [decoded.id]
    );

    const user = rows[0];

    if (!user) {
      return res.status(401).json({
        error: "Hisob topilmadi."
      });
    }

    req.user = user;
    next();

  } catch {
    res.status(401).json({
      error: "Kirish muddati tugagan. Qayta kiring."
    });
  }
}

// Faqat EGA
function faqatEga(req, res, next) {
  if (req.user.role !== "owner") {
    return res.status(403).json({
      error: "Bu amal faqat EGA uchun."
    });
  }

  next();
}

// Admin yoki EGA
function faqatAdmin(req, res, next) {
  if (!["owner", "admin"].includes(req.user.role)) {
    return res.status(403).json({
      error: "Ruxsat yo‘q."
    });
  }

  next();
}

// Ruxsatlarni olish
function ruxsatlar(user) {
  try {
    return JSON.parse(user.permissions || "{}");
  } catch {
    return {};
  }
}


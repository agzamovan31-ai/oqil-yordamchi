-- Neon PostgreSQL migration for users table
-- Intended to preserve the current SQLite auth model while enabling PostgreSQL compatibility.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    permissions TEXT NOT NULL DEFAULT '{}',
    created_by BIGINT,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    CONSTRAINT fk_users_created_by
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        DEFERRABLE INITIALLY DEFERRED
);

-- Case-insensitive uniqueness for username.
-- This keeps SQLite-style behavior by comparing on LOWER(username).
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_lower
    ON users (LOWER(username));

-- Standard role check for application logic.
CREATE INDEX IF NOT EXISTS idx_users_role
    ON users (role);

-- Useful for owner/admin lookups and created-by ownership chains.
CREATE INDEX IF NOT EXISTS idx_users_created_by
    ON users (created_by);
